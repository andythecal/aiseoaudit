CREATE TABLE IF NOT EXISTS schema_versions (version INT PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audits (
 id CHAR(32) PRIMARY KEY,
 visitor_hash CHAR(64) NOT NULL,
 user_id BIGINT UNSIGNED NULL,
 requested_url VARCHAR(2048) NOT NULL,
 final_url VARCHAR(2048) NULL,
 state VARCHAR(16) NOT NULL DEFAULT 'running',
 score SMALLINT UNSIGNED NULL,
 result_json LONGTEXT NULL,
 error_message VARCHAR(500) NULL,
 engine_version VARCHAR(20) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 completed_at TIMESTAMP NULL,
 INDEX visitor_history (visitor_hash, created_at),
 INDEX user_history (user_id, created_at),
 CONSTRAINT audits_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket CHAR(64) PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL DEFAULT 1,
 expires_at DATETIME NOT NULL,
 INDEX rate_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS leads (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 marketing_consent TINYINT(1) NOT NULL DEFAULT 0,
 consent_version VARCHAR(20) NOT NULL,
 consent_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 ghl_contact_id VARCHAR(100) NULL,
 CONSTRAINT leads_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
